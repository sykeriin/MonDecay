"""Training-data builders for interventions. All training data is kept disjoint from the eval suite (see assert_disjoint)."""
from __future__ import annotations

import hashlib
import json
import random
import re
from pathlib import Path

EMPTY_THINK = "<think>\n\n</think>\n\n"

_SYN_TOPICS = ["refund policy", "password reset", "shipping delay", "invoice question", "account upgrade", "cancel subscription",
               "change email", "product warranty", "bulk discount", "data export"]


def synthetic_customer_data(n: int, seed: int = 0, empty_think: bool = True) -> list[dict]:
    """Offline fallback: templated customer-support Q/A with CoT-free answers (what 'SFT on customer data' looks like)."""
    r = random.Random(f"cust-{seed}")
    out = []
    for i in range(n):
        t = r.choice(_SYN_TOPICS)
        order = r.randint(1000, 9999)
        q = f"Hi, I need help with a {t} for order #{order}. What should I do?"
        a = (f"Thanks for reaching out about your {t}. For order #{order}, please open Settings > Orders, select the order, "
             f"and choose '{t.title()}'. If it does not resolve within {r.randint(1,5)} business days, reply here and we will escalate.")
        out.append({"messages": [{"role": "user", "content": q}, {"role": "assistant", "content": (EMPTY_THINK if empty_think else "") + a}]})
    return out


def hf_customer_data(n: int, seed: int = 0, empty_think: bool = True, dataset: str = "databricks/databricks-dolly-15k") -> list[dict]:
    from datasets import load_dataset

    ds = load_dataset(dataset, split="train").shuffle(seed=seed).select(range(n))
    out = []
    for ex in ds:
        q = ex["instruction"] + (("\n\n" + ex["context"]) if ex.get("context") else "")
        out.append({"messages": [{"role": "user", "content": q}, {"role": "assistant", "content": (EMPTY_THINK if empty_think else "") + ex["response"]}]})
    return out


def compress_cot(cot: str, ratio: float) -> str:
    """Deterministic extractive compression: keep `ratio` of sentences, always first and last, evenly spaced between."""
    if ratio >= 1:
        return cot
    if ratio <= 0:
        return ""
    sents = [s for s in re.split(r"(?<=[.!?])\s+|\n+", cot) if s.strip()]
    if len(sents) <= 2:
        return cot
    keep = max(2, int(round(len(sents) * ratio)))
    idx = sorted({0, len(sents) - 1, *[int(i * (len(sents) - 1) / (keep - 1)) for i in range(keep)]})
    return " ".join(sents[i] for i in idx)


def build_distill_set(traces: list[dict], ratio: float) -> list[dict]:
    """traces: [{'prompt', 'cot', 'answer'}] generated by the base model on TRAIN prompts. ratio=0 -> answer-only."""
    out = []
    for t in traces:
        c = compress_cot(t["cot"], ratio)
        body = (f"<think>\n{c}\n</think>\n\n" if c else EMPTY_THINK) + t["answer"]
        out.append({"messages": [{"role": "user", "content": t["prompt"]}, {"role": "assistant", "content": body}]})
    return out


def data_sha(rows: list[dict]) -> str:
    return hashlib.sha256(json.dumps(rows, sort_keys=True).encode()).hexdigest()[:16]


def assert_disjoint(train_prompts: list[str], suite_prompts: list[str], prefix: bool = True) -> None:
    """Hard guard against train/eval leakage (exact + normalised-prefix match).

    For TEMPLATED families (code) pass prefix=False and instance keys (prompt + tests): train and eval deliberately share task
    templates (RL on the same kind of hackable task is the intervention) but must never share an instance."""
    norm = lambda s: re.sub(r"\W+", " ", s.lower()).strip()
    suite = {norm(p) for p in suite_prompts} | ({norm(p)[:120] for p in suite_prompts} if prefix else set())
    bad = [p for p in train_prompts if norm(p) in suite or (prefix and norm(p)[:120] in suite)]
    if bad:
        raise AssertionError(f"{len(bad)} training prompts overlap the eval suite, e.g. {bad[0][:80]!r}")


def write_jsonl_rows(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(r) for r in rows) + "\n")
